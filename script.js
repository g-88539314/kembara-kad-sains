let quiz = {
  id: null,
  index: 0,
  answers: [],
  score: 0
};

function startQuiz(id) {

  if (!state.watched[id]) {

    toast(
      '🎬 Lengkapkan semua 3 video dahulu.'
    );

    return;
  }

  quiz = {
    id: id,
    index: 0,
    answers: [],
    score: 0
  };

  renderQuestion();

  $('#quizPanel').hidden = false;

  $('#quizPanel')
    .scrollIntoView({
      behavior: 'smooth'
    });
}

function renderQuestion() {

  const c =
    characters[quiz.id];

  const q =
    c.questions[quiz.index];

  $('#quizPanel').innerHTML = `

    <div class="quiz-top">

      <b>
        🚀 CABARAN ${c.name}
      </b>

      <span>
        ${quiz.index + 1} / 10
      </span>

    </div>

    <div class="bar">
      <span
        style="
          width:${(quiz.index / 10) * 100}%
        "
      ></span>
    </div>

    <div class="quiz-q">
      ${q[0]}
    </div>

    <div class="answers">

      ${q[1].map((a, i) => `

        <button
          class="answer"
          data-i="${i}"
        >

          ${String.fromCharCode(65 + i)}. ${a}

        </button>

      `).join('')}

    </div>
  `;

  $('#quizPanel')
    .querySelectorAll('.answer')
    .forEach(b => {

      b.onclick =
        () => answer(
          Number(b.dataset.i)
        );

    });
}

function answer(i) {

  const q =
    characters[quiz.id]
      .questions[quiz.index];

  if (i === q[2]) {
    quiz.score++;
  }

  quiz.index++;

  if (quiz.index < 10) {

    renderQuestion();

  } else {

    finishQuiz();
  }
}

function finishQuiz() {

  const c =
    characters[quiz.id];

  const pct =
    quiz.score * 10;

  const passed =
    pct >= 80;

  const already =
    state.completed[quiz.id];

  if (!state.watched[quiz.id]) {

    toast(
      '🔒 Lengkapkan semua video dahulu.'
    );

    return;
  }

  if (passed && !already) {

    state.completed[quiz.id] =
      true;

    state.unlocked[quiz.id] =
      true;

    state.xp += 20;
    state.score += 20;

    save();

  } else {

    save();
  }

  const message =
    passed && already
      ? 'Anda sudah membuka kad ini sebelum ini. Tiada XP tambahan diberikan.'
      : passed
        ? 'Hebat! Kad digital telah dibuka dan +20 XP diberikan.'
        : 'Belum mencapai 80%. Cuba lagi untuk membuka kad!';

  $('#quizPanel').innerHTML = `

    <div class="result">

      <p class="eyebrow">
        CABARAN SELESAI
      </p>

      <h2>
        ${c.name}
        ${passed ? '🎉' : '💪'}
      </h2>

      <div class="big">
        ${quiz.score}/10
      </div>

      <h3>
        ${pct}%
      </h3>

      <p>
        ${message}
      </p>

      ${
        passed && state.unlocked[quiz.id]
          ? `

            <div
              style="
                margin:18px auto;
                max-width:520px;
                padding:12px 16px;
                border-radius:16px;
                background:#fff7d8;
                border:2px solid #f0d56d;
                font-weight:900;
              "
            >
              🎴 KAD ${c.name} BERJAYA DIKUMPUL!
            </div>

            <div
              style="
                max-width:360px;
                margin:0 auto 18px;
              "
            >

              <img
                src="${c.card}"
                alt="Kad ${c.name}"
                style="
                  width:100%;
                  display:block;
                  border-radius:18px;
                "
              >

            </div>

          `
          : ''
      }

      <div
        class="actions"
        style="justify-content:center"
      >

        <button
          class="primary"
          id="again"
        >
          🔄 Cuba Lagi
        </button>

        <button
          class="secondary"
          id="collectionBtn"
        >
          🎴 Lihat Koleksi
        </button>

      </div>

    </div>
  `;

  $('#again').onclick =
    () => startQuiz(quiz.id);

  $('#collectionBtn').onclick = () => {

    render();

    $('#collectionPanel')
      .scrollIntoView({
        behavior: 'smooth'
      });
  };

  render();

  if (passed && !already) {

    toast(
      `🎉 ${c.name} berjaya dibuka! +20 XP`
    );

  } else {

    toast(
      `Skor ${pct}%`
    );
  }
}

function toast(msg) {

  const t = $('#toast');

  t.textContent = msg;

  t.classList.add('show');

  setTimeout(() => {

    t.classList.remove('show');

  }, 2600);
}

