function renderCollection() {
  const g = $('#collectionGrid');

  g.innerHTML = Object.entries(characters)
    .map(([id, c], i) => {

      if (state.unlocked[id]) {
        return `
          <div class="collection-card">
            <img
              src="${c.card}"
              alt="Kad Koleksi ${c.name}"
              title="${c.name}"
            >
          </div>
        `;
      }

      const videoDone = state.watched[id];

      return `
        <div class="collection-card locked">
          <div class="lock">🔒</div>

          <div>
            0${i + 1} — ${c.name}
          </div>

          <small>
            ${
              videoDone
                ? 'Video selesai — lengkapkan cabaran untuk buka'
                : 'Tonton satu video dan lengkapkan cabaran'
            }
          </small>
        </div>
      `;
    })
    .join('');
}

function renderProgress() {
  const g = $('#progressList');

  g.innerHTML = Object.entries(characters)
    .map(([id, c]) => {

      const progress =
        state.videoProgress[id] || [false];

      const doneVideos = progress.filter(Boolean).length;

      let width = '0%';
      let status = 'Belum mula';

      if (state.completed[id]) {
        width = '100%';
        status = 'Kad Dikumpul';
      } else if (state.watched[id]) {
        width = '75%';
        status = 'Video selesai — cabaran dibuka';
      } else if (doneVideos > 0) {
        width = `${20 + doneVideos * 18}%`;
        status = `${doneVideos}/1 video selesai`;
      } else if (state.access[id]) {
        width = '10%';
        status = 'Video pembelajaran tersedia';
      }

      return `
        <div class="progress-row">

          <div>${c.name}</div>

          <div class="bar">
            <span style="width:${width}"></span>
          </div>

          <div>${status}</div>

        </div>
      `;
    })
    .join('');
}

function focusCharacter(id) {
  const c = characters[id];
  const banner = $('#qrBanner');

  if (!banner) return;

  banner.hidden = false;

  banner.innerHTML = `
    🎴 <b>Kad ${c.name} dikesan!</b>
    Jom teruskan misi ${c.concept}.
  `;

  setTimeout(() => {

    document
      .querySelector(`[data-id="${id}"]`)
      ?.scrollIntoView({
        behavior: 'smooth',
        block: 'center'
      });

  }, 200);
}

let youtubeApiPromise = null;
let youtubePlayer = null;

function loadYouTubeAPI() {

  if (window.YT && window.YT.Player) {
    return Promise.resolve();
  }

  if (youtubeApiPromise) {
    return youtubeApiPromise;
  }

  youtubeApiPromise = new Promise(resolve => {

    const previousCallback =
      window.onYouTubeIframeAPIReady;

    window.onYouTubeIframeAPIReady = () => {

      if (typeof previousCallback === 'function') {
        previousCallback();
      }

      resolve();
    };

    const existingScript =
      document.querySelector(
        'script[src="https://www.youtube.com/iframe_api"]'
      );

    if (!existingScript) {

      const tag = document.createElement('script');

      tag.src =
        'https://www.youtube.com/iframe_api';

      document.head.appendChild(tag);
    }
  });

  return youtubeApiPromise;
}

function destroyYouTubePlayer() {

  try {

    if (
      youtubePlayer &&
      typeof youtubePlayer.destroy === 'function'
    ) {
      youtubePlayer.destroy();
    }

  } catch (e) {

    console.warn(
      'YouTube player tidak dapat ditutup dengan sempurna.',
      e
    );
  }

  youtubePlayer = null;
}

function firstIncompleteVideoIndex(id) {

  const progress =
    state.videoProgress[id] ||
    [false];

  for (let i = 0; i < progress.length; i++) {

    if (!progress[i]) {
      return i;
    }
  }

  return 3;
}

function markVideoComplete(id, index) {

  if (!characters[id]) return;

  if (!Array.isArray(state.videoProgress[id])) {

    state.videoProgress[id] =
      [false];
  }

  if (state.videoProgress[id][index]) {
    return;
  }

  state.videoProgress[id][index] = true;

  if (state.videoProgress[id].every(Boolean)) {
    state.watched[id] = true;
  }

  save();

  renderProgress();
  renderCollection();

  const next = index + 1;

  if (next < characters[id].videos.length) {

    toast(
      `✅ ${characters[id].videos[index].title} selesai! Video seterusnya dibuka.`
    );

    openLearn(id);

  } else {

    toast(
      `🎉 Video ${characters[id].name} telah selesai! Cabaran dibuka.`
    );

    openLearn(id);
  }
}

function createYouTubePlayer(id, videoIndex) {

  const c = characters[id];
  const video = c.videos[videoIndex];

  if (!video) return;

  loadYouTubeAPI()
    .then(() => {

      const playerElementId =
        `yt-player-${id}-${videoIndex}`;

      const target =
        document.getElementById(
          playerElementId
        );

      if (!target) return;

      youtubePlayer =
        new YT.Player(
          playerElementId,
          {

            videoId: video.id,

            playerVars: {
              autoplay: 0,
              controls: 1,
              disablekb: 0,
              rel: 0,
              fs: 0,
              playsinline: 1
            },

            events: {

              onReady: event => {

                const overlay =
                  document.getElementById(
                    'videoInstruction'
                  );

                if (overlay) {

                  overlay.textContent =
                    'Tekan ▶️ untuk mula menonton video.';
                }
              },

              onStateChange: event => {

                if (
                  event.data ===
                  YT.PlayerState.ENDED
                ) {

                  markVideoComplete(
                    id,
                    videoIndex
                  );
                }
              }
            }
          }
        );
    })
    .catch(err => {

      console.error(
        'YouTube API gagal dimuatkan:',
        err
      );

      const status =
        document.getElementById(
          'videoStatus'
        );

      if (status) {

        status.textContent =
          '⚠️ Video tidak dapat dimuatkan. Sila semak tetapan embedding video YouTube.';
      }
    });
}

