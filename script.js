const VIDEO_VERSION = 'kks-video-game-gate-v2';

const EMPTY_FLAGS = () => ({
  nafasio: false,
  kumuhrion: false,
  tinjatron: false,
  impulso: false
});

const EMPTY_VIDEO_PROGRESS = () => ({
  nafasio: [false],
  kumuhrion: [false],
  tinjatron: [false],
  impulso: [false]
});

let state = {
  name: '',
  id: '',
  xp: 0,
  score: 0,
  active: null,
  access: EMPTY_FLAGS(),
  watched: EMPTY_FLAGS(),
  gamePassed: EMPTY_FLAGS(),
  gameResult: null,
  videoProgress: EMPTY_VIDEO_PROGRESS(),
  completed: EMPTY_FLAGS(),
  unlocked: EMPTY_FLAGS(),
  videoVersion: VIDEO_VERSION
};

const $ = s => document.querySelector(s);

function save() {
  try {
    localStorage.setItem(
      'kembaraState',
      JSON.stringify(state)
    );
  } catch (error) {
    console.warn(
      'Data tidak dapat disimpan pada peranti ini. Website terus berjalan tanpa penyimpanan kekal.',
      error
    );
  }
}

function normalizeState() {
  state.access = { ...EMPTY_FLAGS(), ...(state.access || {}) };
  state.watched = { ...EMPTY_FLAGS(), ...(state.watched || {}) };
  state.gamePassed = { ...EMPTY_FLAGS(), ...(state.gamePassed || {}) };
  state.completed = { ...EMPTY_FLAGS(), ...(state.completed || {}) };
  state.unlocked = { ...EMPTY_FLAGS(), ...(state.unlocked || {}) };

  const freshProgress = EMPTY_VIDEO_PROGRESS();

  Object.keys(freshProgress).forEach(id => {
    const existing =
      state.videoProgress && Array.isArray(state.videoProgress[id])
        ? state.videoProgress[id]
        : [];

    state.videoProgress[id] = [existing[0] === true];
  });
}

function load() {
  let raw = null;

  try {
    raw = localStorage.getItem('kembaraState');
  } catch (error) {
    console.warn(
      'localStorage tidak tersedia. Website akan menggunakan data sementara.',
      error
    );
  }

  if (raw) {
    try {
      const old = JSON.parse(raw);

      state = {
        ...state,
        ...old
      };

      // Pautan video telah ditukar. Reset status tontonan lama supaya
      // murid perlu menonton video baharu bagi setiap wira sekali sahaja.
      if (state.videoVersion !== VIDEO_VERSION) {
        state.videoProgress = EMPTY_VIDEO_PROGRESS();
        state.watched = EMPTY_FLAGS();
        state.gamePassed = EMPTY_FLAGS();
        state.gameResult = null;
        state.videoVersion = VIDEO_VERSION;
      }
    } catch (error) {
      console.warn(
        'Data lama tidak dapat dibaca. Menggunakan state baharu.',
        error
      );
    }
  }

  normalizeState();

  const p =
    new URLSearchParams(
      location.search
    ).get('card');

  if (p && characters[p]) {
    state.active = p;
    state.access[p] = true;
    save();
  }
}

function render() {
  normalizeState();

  $('#headerName').textContent = state.name || 'Murid';
  $('#headerId').textContent = state.id || '—';

  $('#welcomeText').textContent = state.name
    ? `${state.name}! Teruskan misi anda dan kumpulkan semua kad digital!`
    : 'Jom mulakan misi dan kumpulkan semua kad digital!';

  $('#xp').textContent = state.xp;
  $('#score').textContent = state.score;
  $('#cards').textContent = Object.values(state.unlocked).filter(Boolean).length;
  $('#missions').textContent = Object.values(state.completed).filter(Boolean).length;

  renderHeroes();
  renderCollection();
  renderProgress();

  if (state.active) {
    focusCharacter(state.active);
  }
}

